create table ingredients (
    id   bigint primary key generated by default as identity,
    code varchar(50)  not null unique,
    name varchar(200) not null,
    unit varchar(10)  not null check (unit in ('ML', 'G', 'PCS'))
);

create table modifiers (
    id                bigint primary key generated by default as identity,
    code              varchar(50)  not null unique,
    name              varchar(200) not null,
    category          varchar(20)  not null check (category in ('MILK', 'SYRUP', 'EXTRA_SHOT', 'TOPPING')),
    price_rubles     numeric(10, 2) not null check (price_rubles >= 0),
    ingredient_id     bigint       not null references ingredients (id),
    quantity_per_unit integer      not null check (quantity_per_unit >= 0)
);

create table base_drinks (
    id                       bigint primary key generated by default as identity,
    code                     varchar(50)   not null unique,
    name                     varchar(200)  not null,
    description              varchar(1000) not null,
    milk_portion             integer       not null default 0 check (milk_portion >= 0),
    default_milk_modifier_id bigint references modifiers (id)
);

create table base_drink_sizes (
    base_drink_id        bigint     not null references base_drinks (id),
    size                 varchar(2) not null check (size in ('S', 'M', 'L')),
    price_rubles        numeric(10, 2) not null check (price_rubles > 0),
    volume_ml            integer    not null check (volume_ml > 0),
    recipe_scale_percent integer    not null check (recipe_scale_percent > 0),
    primary key (base_drink_id, size)
);

create table base_drink_temperatures (
    base_drink_id bigint      not null references base_drinks (id),
    temperature   varchar(10) not null check (temperature in ('HOT', 'ICED')),
    primary key (base_drink_id, temperature)
);

create table base_drink_ingredients (
    base_drink_id bigint  not null references base_drinks (id),
    ingredient_id bigint  not null references ingredients (id),
    quantity      integer not null check (quantity > 0),
    primary key (base_drink_id, ingredient_id)
);

create table base_drink_modifier_limits (
    base_drink_id bigint      not null references base_drinks (id),
    category      varchar(20) not null check (category in ('MILK', 'SYRUP', 'EXTRA_SHOT', 'TOPPING')),
    min_count     integer     not null check (min_count >= 0),
    max_count     integer     not null,
    primary key (base_drink_id, category),
    check (max_count >= min_count)
);
