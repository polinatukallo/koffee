create table orders (
    id            bigint primary key generated by default as identity,
    customer_name varchar(100) not null,
    status        varchar(20)  not null
        check (status in ('CREATED', 'ACCEPTED', 'IN_PROGRESS', 'READY', 'COMPLETED', 'CANCELLED')),
    total_rubles numeric(10, 2) not null check (total_rubles >= 0),
    created_at    timestamptz  not null,
    updated_at    timestamptz  not null,
    version       bigint       not null default 0
);

create index idx_orders_created on orders (created_at desc);
create index idx_orders_status_created on orders (status, created_at desc);

create table order_lines (
    id                 bigint primary key generated by default as identity,
    order_id           bigint       not null references orders (id) on delete cascade,
    line_no            integer      not null,
    base_drink_id      bigint       not null,
    drink_name         varchar(200) not null,
    size               varchar(2)   not null,
    temperature        varchar(10)  not null,
    volume_ml          integer      not null,
    unit_price_rubles numeric(10, 2) not null check (unit_price_rubles >= 0),
    quantity           integer      not null check (quantity between 1 and 10),
    unique (order_id, line_no)
);

create table order_line_modifiers (
    order_line_id      bigint       not null references order_lines (id) on delete cascade,
    position           integer      not null,
    modifier_id        bigint       not null,
    name               varchar(200) not null,
    category           varchar(20)  not null,
    quantity           integer      not null check (quantity > 0),
    unit_price_rubles numeric(10, 2) not null check (unit_price_rubles >= 0),
    primary key (order_line_id, position)
);

create table order_status_history (
    id         bigint primary key generated by default as identity,
    order_id   bigint      not null references orders (id) on delete cascade,
    status     varchar(20) not null,
    changed_at timestamptz not null
);

create index idx_order_status_history_order on order_status_history (order_id);
